// Geometry and LaTeX source for handout.mjs (issue #34). Pure functions, so the tests can check
// the numbers without running XeLaTeX. All lengths are millimetres, measured from the page's top-left corner.

// The two presets, chosen by orientation: landscape A4 2 × 2, portrait A4 3 rows × 2 columns.
export const PRESETS = { landscape: { rows: 2, cols: 2 }, portrait: { rows: 3, cols: 2 } };
export const A4 = { landscape: { paperW: 297, paperH: 210 }, portrait: { paperW: 210, paperH: 297 } };

// Tried in order when the header title contains CJK text and no --cjk-font was given:
// macOS ships the first two; the Noto and Source Han families cover Linux and Windows installs.
export const CJK_FONTS = ['PingFang TC', 'Heiti TC', 'Noto Sans CJK TC', 'Source Han Sans TC', 'Noto Sans TC'];
const CJK = /[⺀-鿿가-힯豈-﫿＀-￯]/;

// Slide width = min((W − 2m − (c−1)g) / c, ((H − 2m − bands − (r−1)g) / r) × aspect); the grid is then
// centred. The header and footer bands come off the height only, so they change nothing on a page
// whose slides are bound by the width (both presets are).
export function geometry({ paperW, paperH, rows, cols, margin = 12, gap = 8, aspect = 16 / 9, headerBand = 0, footerBand = 0 }) {
  const availW = paperW - 2 * margin;
  const availH = paperH - 2 * margin - headerBand - footerBand;
  const byWidth = (availW - (cols - 1) * gap) / cols;
  const byHeight = ((availH - (rows - 1) * gap) / rows) * aspect;
  const slideW = Math.min(byWidth, byHeight);
  if (!(slideW > 0)) {
    throw new RangeError(`a ${rows} × ${cols} grid does not fit on a ${paperW} × ${paperH} mm page with ${margin} mm margins and ${gap} mm gaps`);
  }
  const slideH = slideW / aspect;
  const gridW = cols * slideW + (cols - 1) * gap;
  const gridH = rows * slideH + (rows - 1) * gap;
  const left = (paperW - gridW) / 2;
  const top = margin + headerBand + (availH - gridH) / 2;
  const cells = [];
  for (let r = 0; r < rows; r++) {
    for (let c = 0; c < cols; c++) cells.push({ x: left + c * (slideW + gap), y: top + r * (slideH + gap) });
  }
  return { slideW, slideH, left, top, gridW, gridH, cells, bound: byWidth <= byHeight ? 'width' : 'height' };
}

const ESCAPES = {
  '\\': '\\textbackslash{}', '{': '\\{', '}': '\\}', '$': '\\$', '&': '\\&', '#': '\\#', '%': '\\%', '_': '\\_',
  '~': '\\textasciitilde{}', '^': '\\textasciicircum{}',
};

// One pass over the string, so an escape is never escaped again; line breaks become spaces.
export function texEscape(text) {
  return String(text).replace(/\s*\n\s*/g, ' ').replace(/[\\{}$&#%_~^]/g, (ch) => ESCAPES[ch]);
}

function cjkPreamble(title, cjkFont) {
  if (!CJK.test(title)) return [];
  const use = (name) => `\\setCJKmainfont{${name}}\\setCJKsansfont{${name}}`;
  if (cjkFont) return ['\\usepackage{xeCJK}', use(cjkFont)];
  // handout.mjs looks for this message in the log to print a hint instead of a bare LaTeX error.
  const chain = CJK_FONTS.reduceRight(
    (otherwise, name) => `\\IfFontExistsTF{${name}}{${use(name)}}{${otherwise}}`,
    '\\errmessage{HANDOUT: no CJK font found}',
  );
  return ['\\usepackage{xeCJK}', chain];
}

const mm = (v) => +v.toFixed(3);

// One page per sheet. Each slide is a TikZ node placed at absolute page coordinates; the frame is
// drawn around the node, so it hugs the actual slide image even when the deck is not 16:9.
export function texFor({
  geometry: g, paperW, paperH, pages, deck = 'deck.pdf',
  frame = true, frameWidth = 0.4, title = '', pageNumbers = true, cjkFont = '',
}) {
  const perSheet = g.cells.length;
  const sheets = Math.ceil(pages / perSheet);
  const lines = [
    '% Generated by handout.mjs (academic-slides, issue #34). Coordinates are mm from the top-left corner.',
    '\\documentclass{article}',
    `\\usepackage[paperwidth=${paperW}mm,paperheight=${paperH}mm,margin=0mm]{geometry}`,
    '\\usepackage{graphicx}',
    '\\usepackage{tikz}',
    '\\usepackage{fontspec}',
    ...cjkPreamble(title, cjkFont),
    '\\pagestyle{empty}',
    '\\setlength{\\parindent}{0pt}',
    '\\begin{document}',
  ];
  const box = frame ? `draw=black, line width=${frameWidth}pt, ` : '';
  for (let s = 0; s < sheets; s++) {
    lines.push('\\begin{tikzpicture}[remember picture, overlay, x=1mm, y=-1mm, shift={(current page.north west)}]');
    for (let i = 0; i < perSheet && s * perSheet + i < pages; i++) {
      const c = g.cells[i];
      lines.push(`  \\node[${box}inner sep=0pt, outer sep=0pt] at (${mm(c.x + g.slideW / 2)}, ${mm(c.y + g.slideH / 2)}) `
        + `{\\includegraphics[page=${s * perSheet + i + 1}, width=${mm(g.slideW)}mm, height=${mm(g.slideH)}mm, keepaspectratio]{${deck}}};`);
    }
    if (title) {
      // As wide as the grid, so a long title (Quarto appends the subtitle to the PDF title) wraps upward
      // into the margin instead of running off the page.
      lines.push(`  \\node[anchor=south west, inner sep=0pt, text width=${mm(g.gridW)}mm, align=left, font=\\small\\sffamily] `
        + `at (${mm(g.left)}, ${mm(g.top - 3)}) {${texEscape(title)}};`);
    }
    if (pageNumbers) {
      lines.push(`  \\node[anchor=north, inner sep=0pt, font=\\small\\sffamily] at (${mm(paperW / 2)}, ${mm(g.top + g.gridH + 3)}) {${s + 1} / ${sheets}};`);
    }
    lines.push('\\end{tikzpicture}', '\\clearpage');
  }
  lines.push('\\end{document}', '');
  return lines.join('\n');
}
